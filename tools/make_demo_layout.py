"""Regenerate ui/demo-layout.js from models.py and the layout files (demo mode runs from file://, where fetch is
blocked): every model with its keys, so demo mode can show each one (ui/index.html?demo&model=02B0)."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "ui", "demo-layout.js")
sys.path.insert(0, ROOT)


def read_models():
    import models
    out = []
    for m in models.MODELS.values():
        with open(os.path.join(ROOT, m.layout), encoding="utf-8") as f:
            out.append({**m.info(), "layout": json.load(f)})
    return out


def render(data):
    return ("// SPDX-License-Identifier: GPL-3.0-or-later\n"
            "// Copyright (C) 2026 Huntsman for Mac contributors\n"
            "// Generated by tools/make_demo_layout.py from models.py and the layout files. Do not edit.\n"
            "window.DEMO_MODELS = " + json.dumps(data) + ";\n"
            "window.DEMO_LAYOUT = window.DEMO_MODELS[0].layout;\n")


def main():
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(render(read_models()))


if __name__ == "__main__":
    main()
