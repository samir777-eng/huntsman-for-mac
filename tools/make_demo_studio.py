"""Regenerate ui/demo-studio.js: the effect catalogue and built-in presets, so demo mode shows the real ones."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "ui", "demo-studio.js")
sys.path.insert(0, ROOT)


def read_studio():
    import studio
    from lighting.presets import builtin_presets
    return {"effects": studio.effect_catalog(), "presets": [p.to_dict() for p in builtin_presets()]}


def render(data):
    return ("// SPDX-License-Identifier: GPL-3.0-or-later\n"
            "// Copyright (C) 2026 Huntsman for Mac contributors\n"
            "// Generated by tools/make_demo_studio.py from lighting/ and studio.py. Do not edit.\n"
            "window.DEMO_STUDIO = " + json.dumps(data) + ";\n")


def main():
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(render(read_studio()))


if __name__ == "__main__":
    main()
