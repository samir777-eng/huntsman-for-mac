"""Regenerate ui/demo-layout.js from layout.json (demo mode runs from file://, where fetch is blocked)."""
import json
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with open(os.path.join(root, "layout.json")) as f:
    layout = json.load(f)
with open(os.path.join(root, "ui", "demo-layout.js"), "w") as f:
    f.write("// Generated by tools/make_demo_layout.py from layout.json. Do not edit.\n")
    f.write("window.DEMO_LAYOUT = " + json.dumps(layout) + ";\n")
