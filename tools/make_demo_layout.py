"""Regenerate ui/demo-layout.js from layout.json (demo mode runs from file://, where fetch is blocked)."""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "ui", "demo-layout.js")


def read_layout():
    with open(os.path.join(ROOT, "layout.json")) as f:
        return json.load(f)


def render(layout):
    return ("// SPDX-License-Identifier: GPL-3.0-or-later\n"
            "// Copyright (C) 2026 Huntsman for Mac contributors\n"
            "// Generated by tools/make_demo_layout.py from layout.json. Do not edit.\n"
            "window.DEMO_LAYOUT = " + json.dumps(layout) + ";\n")


def main():
    with open(OUT, "w") as f:
        f.write(render(read_layout()))


if __name__ == "__main__":
    main()
